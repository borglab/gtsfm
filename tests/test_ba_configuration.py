"""Verify classical leaf, merge, and final BA calibration through real Hydra composition."""

from dataclasses import asdict
from pathlib import Path

import hydra
import pytest
from omegaconf import OmegaConf

from gtsfm.bundle.bundle_adjustment import BundleAdjustmentOptions, RobustBAMode

CLASSICAL_CONFIGS = [
    "colmap_front_end",
    "deep_front_end",
    "deep_front_end_astrovision",
    "deep_front_end_hilti",
    "megaloc_sift_frontend",
    "megaloc_sift_gp_metis",
    "megaloc_sift_gp_single",
    "megaloc_sift_metis",
    "megaloc_sift_single",
    "onedsfm_front_end",
    "scene_optimizer_unit_test_config",
    "sift_front_end",
    "sift_front_end_astrovision",
    "sift_global_positioner",
    "skydio_front_end",
    "synthetic_front_end",
    "unified",
    "unified_binary",
    "unified_megaloc",
]
LEAF_PATH = "cluster_optimizer.multiview_optimizer.bundle_adjustment_module"
CALIBRATION_FIELDS = (
    "shared_calib",
    "use_calibration_prior",
    "calibration_prior_focal_sigma",
    "calibration_prior_dist_sigma",
    "calibration_prior_pp_sigma",
)


def _compose(name: str, overrides: list[str]):
    """Compose the same config module used by the runner without loading models or images."""
    with hydra.initialize_config_module(config_module="gtsfm.configs", version_base=None):
        return hydra.compose(config_name=name, overrides=overrides)


@pytest.mark.parametrize("name", CLASSICAL_CONFIGS)
@pytest.mark.parametrize(
    "overrides",
    [
        [],
        # This is the override generated by the runner's --share_intrinsics flag.
        [f"{LEAF_PATH}.shared_calib=True"],
        [
            f"{LEAF_PATH}.shared_calib=False",
            f"{LEAF_PATH}.use_calibration_prior=False",
            f"{LEAF_PATH}.calibration_prior_focal_sigma=7.0",
            f"{LEAF_PATH}.calibration_prior_dist_sigma=[0.2,0.3]",
            f"{LEAF_PATH}.calibration_prior_pp_sigma=0.001",
        ],
    ],
)
def test_classical_ba_calibration_agrees_across_stages(name: str, overrides: list[str]) -> None:
    """Default values and command-line calibration overrides reach actual BA optimizers."""
    cfg = _compose(name, overrides)
    leaf = hydra.utils.instantiate(OmegaConf.select(cfg, LEAF_PATH))
    merging = hydra.utils.instantiate(cfg.merging_options)
    final = merging.ba_options.to_optimizer()
    for key in CALIBRATION_FIELDS:
        assert getattr(leaf, f"_{key}") == getattr(final, f"_{key}")
    # Hydra's persisted resolved config must show the same values used by the optimizers.
    snapshot = OmegaConf.to_container(cfg, resolve=True)
    for key in CALIBRATION_FIELDS:
        assert snapshot["merging_options"]["ba_options"][key] == getattr(merging.ba_options, key)


@pytest.mark.parametrize("name", CLASSICAL_CONFIGS)
def test_existing_leaf_calibration_and_solver_choices_are_preserved(name: str) -> None:
    """Adding shared defaults must not change existing leaf calibration or solver choices."""
    original = OmegaConf.load(Path(__file__).parents[1] / "gtsfm" / "configs" / f"{name}.yaml")
    original_leaf = hydra.utils.instantiate(OmegaConf.select(original, LEAF_PATH))
    cfg = _compose(name, [])
    leaf = hydra.utils.instantiate(OmegaConf.select(cfg, LEAF_PATH))
    for key in CALIBRATION_FIELDS + ("robust_ba_mode", "measurement_noise_sigma", "reproj_error_thresholds"):
        assert getattr(original_leaf, f"_{key}") == getattr(leaf, f"_{key}")
    merging = hydra.utils.instantiate(cfg.merging_options)
    if name in ("megaloc_sift_metis", "megaloc_sift_gp_metis"):
        assert not merging.ba_options.use_calibration_prior
        assert merging.ba_options.use_gnc
        assert merging.ba_options.gnc_loss == "TLS"
        assert merging.ba_options.factor_weight_outlier_threshold == 1e-8
    else:
        assert merging.ba_options.robust_ba_mode == RobustBAMode.GMC
        assert not merging.ba_options.use_gnc


def test_unified_matches_successful_recovery_benchmark_options() -> None:
    """Config wiring reproduces every merge BA option used for the six successful reruns."""
    cfg = _compose("unified", [f"{LEAF_PATH}.shared_calib=True"])
    merging = hydra.utils.instantiate(cfg.merging_options)
    expected = BundleAdjustmentOptions(
        shared_calib=True,
        use_calibration_prior=True,
        calibration_prior_focal_sigma=20.0,
        calibration_prior_dist_sigma=0.1,
        calibration_prior_pp_sigma=1e-5,
    )
    assert asdict(merging.ba_options) == asdict(expected)
    # Keep the different robust losses configured for the different optimization stages.
    leaf = hydra.utils.instantiate(OmegaConf.select(cfg, LEAF_PATH))
    assert leaf._robust_ba_mode == RobustBAMode.HUBER
    assert merging.ba_options.robust_ba_mode == RobustBAMode.GMC


def test_merge_specific_settings_remain_configurable() -> None:
    """Calibration references do not overwrite independent merge solver and pose settings."""
    cfg = _compose(
        "unified",
        [
            f"{LEAF_PATH}.shared_calib=True",
            "+merging_options.ba_options.use_pose_prior_all_cameras=True",
            "+merging_options.ba_options.robust_ba_mode=HUBER",
            "+merging_options.ba_options.min_track_length=4",
        ],
    )
    options = hydra.utils.instantiate(cfg.merging_options).ba_options
    assert options.shared_calib
    assert options.use_calibration_prior
    assert options.use_pose_prior_all_cameras
    assert options.robust_ba_mode == "HUBER"
    assert options.min_track_length == 4
